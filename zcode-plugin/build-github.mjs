// build-github.mjs —— GitHub 后端房间:把上游只读树里房间入口(src/tracker/rooms/github/room/index.ts)
// 连同它的依赖图打成一个 ESM bundle(dist/github-room.mjs)。装机不依赖上游树,构建期克隆。
//
// 解析规则(与 build-git.mjs 同款;依赖闭包 87 个上游文件,外部说明符只有一个 node:async_hooks):
//   1. 相对说明符的 `.js` → 同目录同名 `.ts`(上游 ts-hook 的构建期等价物;找不到就报错,不静默)。
//   2. 任何 `.../time-config/values.js` 或 `.../time-config/src/values.js` → 生成器产物
//      `.tmp/upstream-gen/src/shared/time-config/src/values.ts`(值只来自 config/timeouts.yaml)。
//   3. 第三类特殊依赖:目前没有。node: 内建由 external:["node:*"] 覆盖,闭包里也没有 build-git 那
//      两处宿主垫片(refresh/rooms/host/outbound-admission、gh-execution)需要替换。日后闭包里出现新
//      的特殊说明符,在这里逐条登记并在 onResolve 里显式处理;处理不了就让构建失败并报清楚,
//      不许用空壳顶替。
// 上游树只读;产物 dist/github-room.mjs 入库。用法:node build-github.mjs(build.mjs 会在 git bundle 之后调它)。
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { generateUpstreamLeaves } from "./build-upstream.mjs";

const ROOT = dirname(fileURLToPath(import.meta.url)); // zcode-plugin/
const GEN_VALUES = join(ROOT, ".tmp", "upstream-gen", "src", "shared", "time-config", "src", "values.ts");
const ENTRY = join(ROOT, "src", "github-entry.mjs");
const OUT = join(ROOT, "dist", "github-room.mjs");
// dist/github-entry.mjs 是由 src/github-entry.mjs 直拷的,源码树里的 import 指向上游 TS 图;
// dist 里用一行转出指向 bundle(与 dist/git-entry.mjs 同款)。
const OUT_ENTRY_SHIM = join(ROOT, "dist", "github-entry.mjs");

const TS_JS_RE = /^\.{1,2}\/.*\.js$/;
const TIME_CONFIG_RE = /(?:^|\/)time-config\/(?:src\/)?values\.js$/;

/** 解析插件:上游 TS 图 + 时间参数生成物。顺序有意义(专用别名先于通用 .js→.ts)。 */
function upstreamPlugins() {
  return [
    {
      name: "upstream-time-config",
      setup(build) {
        build.onResolve({ filter: TIME_CONFIG_RE }, () => {
          if (!existsSync(GEN_VALUES)) {
            throw new Error(
              "[build-github] 找不到生成的时间参数 " + GEN_VALUES + ":先跑 buildUpstreamBundle()/generateUpstreamLeaves()"
            );
          }
          return { path: GEN_VALUES };
        });
      },
    },
    {
      name: "upstream-ts-siblings",
      setup(build) {
        build.onResolve({ filter: TS_JS_RE }, (args) => {
          if (!args.resolveDir) return null;
          const candidate = resolve(args.resolveDir, args.path.replace(/\.js$/, ".ts"));
          if (existsSync(candidate)) return { path: candidate };
          return {
            errors: [
              {
                text:
                  "[build-github] " + args.path + " 找不到同目录同名 .ts(上游 ts-hook 约定);解析目录:" + args.resolveDir,
              },
            ],
          };
        });
      },
    },
  ];
}

/** 上游生成物(values.ts)缺失时补跑生成器;已在则复用 build-upstream 的镜像(幂等)。 */
function ensureTimeConfig() {
  if (existsSync(GEN_VALUES)) return;
  console.log("[build-github] 时间参数生成物缺失,先跑上游生成器镜像…");
  generateUpstreamLeaves();
}

/** 打 bundle。返回产物路径。 */
export async function buildGithubBundle() {
  if (!existsSync(ENTRY)) throw new Error("[build-github] 入口不存在:" + ENTRY);
  ensureTimeConfig();
  mkdirSync(dirname(OUT), { recursive: true });
  rmSync(OUT, { force: true });
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    plugins: upstreamPlugins(),
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    external: ["node:*"],
    minify: false, // 产物给人读:上游房间的注释与结构保留
    charset: "utf8",
    allowOverwrite: true,
    metafile: true, // 只为报出依赖闭包大小(上游升级时按文件对账的入口)
    outfile: OUT,
    banner: {
      js:
        "// AUTO-GENERATED by node build-github.mjs — DO NOT EDIT.\n" +
        "// 上游真源(只读):src/tracker/rooms/github/room/index.ts 及其依赖图(src/tracker/**、src/shared/**、src/refresh/contract/**);\n" +
        "// 入口:src/github-entry.mjs(只转出房间对外成员)。\n" +
        "// 解析规则:相对 `.js` 说明符 → 同目录同名 `.ts`(上游 ts-hook 约定);time-config/values.js →\n" +
        "// 生成器产物 .tmp/upstream-gen/src/shared/time-config/src/values.ts(值源 config/timeouts.yaml);\n" +
        "// node: 内建外部化。除此之外没有第三类特殊依赖。\n",
    },
  });
  const code = readFileSync(OUT, "utf8");
  // 语法门禁:按 ESM 解析(node --check 对 .mjs 按模块解析),只解析不执行。
  const check = spawnSync(process.execPath, ["--check", OUT], { encoding: "utf8" });
  if (check.status !== 0) {
    throw new Error("[build-github] dist/github-room.mjs 语法检查失败:" + String((check.stderr || check.stdout || "").trim()).slice(0, 800));
  }
  writeFileSync(
    OUT_ENTRY_SHIM,
    "// AUTO-GENERATED by node build-github.mjs — dist 入口指向 bundle(dist 里的 import 路径)。\n" +
      'export * from "./github-room.mjs";\n',
    "utf8"
  );
  // 源目录不散落 dist(build.mjs 会把 src/ 一并直拷进来;装机只认 bundle 与一行入口)。
  rmSync(join(ROOT, "dist", "github"), { recursive: true, force: true });
  // metafile.inputs 含入口自身与时间参数生成物;上游文件 = 其余以 "../src/" 开头的那些。
  const inputs = Object.keys(result.metafile.inputs).map((p) => p.replace(/\\/g, "/"));
  const upstream = inputs.filter((p) => p.startsWith("../src/")).length;
  console.log(
    "[build-github] dist/github-room.mjs(" +
      code.length +
      " 个字符,code.length(UTF-16 码元);上游依赖闭包 " +
      upstream +
      " 个文件 + 1 个时间参数生成物;入口 " +
      ENTRY +
      ")"
  );
  return OUT;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildGithubBundle().catch((e) => {
    console.error(e && e.stack ? e.stack : e);
    process.exit(1);
  });
}
