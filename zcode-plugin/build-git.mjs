// build-git.mjs —— 版本管理宿主底座:把上游 vc 家族(src/host/versionControl*.ts、stallWatch/fsAbsence/
// runningMarkers、src/shared/version-control/**)与插件自有垫片打成一个 ESM bundle(dist/git.mjs)。
//
// 解析规则(工单 01):
//   1. 相对说明符的 `.js` → 同目录同名 `.ts`(上游 ts-hook 的构建期等价物;找不到就报错,不静默)。
//   2. 任何 `.../time-config/values.js` 或 `.../time-config/src/values.js` → 生成器产物
//      `.tmp/upstream-gen/src/shared/time-config/src/values.ts`(值只来自 config/timeouts.yaml)。
//   3. `../refresh/rooms/host/outbound-admission.js` → src/git/admission-stub.mjs(直通 withGhLane)。
//   4. `../refresh/rooms/host/gh-execution.js` → src/git/credential-safe.mjs(只拷 createCredentialSafeGit)。
// 上游树只读;产物 dist/git.mjs 入库。用法:node build-git.mjs(build.mjs 会在上游 bundle 之后调它)。
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { generateUpstreamLeaves } from "./build-upstream.mjs";

const ROOT = dirname(fileURLToPath(import.meta.url)); // zcode-plugin/
const GEN_VALUES = join(ROOT, ".tmp", "upstream-gen", "src", "shared", "time-config", "src", "values.ts");
const ENTRY = join(ROOT, "src", "git-entry.mjs");
const OUT = join(ROOT, "dist", "git.mjs");
// dist/server.mjs 是由 src/server.mjs 直拷的,它 import "./git-entry.mjs";dist 里用一行转出指向 bundle,
// 源码树与产物树各自可运行(src 里是真入口,dist 里是 bundle)。
const OUT_ENTRY_SHIM = join(ROOT, "dist", "git-entry.mjs");

const TS_JS_RE = /^\.{1,2}\/.*\.js$/;
const TIME_CONFIG_RE = /(?:^|\/)time-config\/(?:src\/)?values\.js$/;
const ADMISSION_RE = /(?:^|\/)refresh\/rooms\/host\/outbound-admission\.js$/;
const GH_EXECUTION_RE = /(?:^|\/)refresh\/rooms\/host\/gh-execution\.js$/;

/** 解析插件:上游 TS 图 + 三处垫片。顺序有意义(专用别名先于通用 .js→.ts)。 */
function upstreamPlugins() {
  return [
    {
      name: "upstream-time-config",
      setup(build) {
        build.onResolve({ filter: TIME_CONFIG_RE }, () => {
          if (!existsSync(GEN_VALUES)) {
            throw new Error(
              "[build-git] 找不到生成的时间参数 " + GEN_VALUES + ":先跑 buildUpstreamBundle()/generateUpstreamLeaves()"
            );
          }
          return { path: GEN_VALUES };
        });
      },
    },
    {
      name: "upstream-host-shims",
      setup(build) {
        build.onResolve({ filter: ADMISSION_RE }, () => ({ path: join(ROOT, "src", "git", "admission-stub.mjs") }));
        build.onResolve({ filter: GH_EXECUTION_RE }, () => ({ path: join(ROOT, "src", "git", "credential-safe.mjs") }));
      },
    },
    {
      name: "upstream-ts-siblings",
      setup(build) {
        build.onResolve({ filter: TS_JS_RE }, (args) => {
          if (!args.resolveDir) return null;
          const candidate = resolve(args.resolveDir, args.path.replace(/\.js$/, ".ts"));
          if (existsSync(candidate)) return { path: candidate };
          return {
            errors: [
              {
                text:
                  "[build-git] " + args.path + " 找不到同目录同名 .ts(上游 ts-hook 约定);解析目录:" + args.resolveDir,
              },
            ],
          };
        });
      },
    },
  ];
}

/** 上游生成物(values.ts)缺失时补跑生成器;已在则复用 build-upstream 的镜像(幂等)。 */
function ensureTimeConfig() {
  if (existsSync(GEN_VALUES)) return;
  console.log("[build-git] 时间参数生成物缺失,先跑上游生成器镜像…");
  generateUpstreamLeaves();
}

/** 打 bundle。返回产物路径。 */
export async function buildGitBundle() {
  if (!existsSync(ENTRY)) throw new Error("[build-git] 入口不存在:" + ENTRY);
  ensureTimeConfig();
  mkdirSync(dirname(OUT), { recursive: true });
  rmSync(OUT, { force: true });
  await esbuild.build({
    entryPoints: [ENTRY],
    plugins: upstreamPlugins(),
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node18",
    external: ["node:*"],
    minify: false, // 产物给人读:上游 vc 家族的注释与结构保留
    charset: "utf8",
    allowOverwrite: true,
    outfile: OUT,
    banner: {
      js:
        "// AUTO-GENERATED by node build-git.mjs — DO NOT EDIT.\n" +
        "// 上游真源(只读):src/host/versionControl*.ts + stallWatch/fsAbsence/runningMarkers + src/shared/version-control/**;\n" +
        "// 垫片:src/git-entry.mjs(Node 服务垫片 + bridge)、src/git/admission-stub.mjs、src/git/credential-safe.mjs。\n" +
        "// 时间参数来自 config/timeouts.yaml(生成器镜像 .tmp/upstream-gen),构建期打进本 bundle。\n",
    },
  });
  const code = readFileSync(OUT, "utf8");
  // 语法门禁:按 ESM 解析(node --check 对 .mjs 按模块解析),只解析不执行。
  const check = spawnSync(process.execPath, ["--check", OUT], { encoding: "utf8" });
  if (check.status !== 0) {
    throw new Error("[build-git] dist/git.mjs 语法检查失败:" + String((check.stderr || check.stdout || "").trim()).slice(0, 800));
  }
  writeFileSync(
    OUT_ENTRY_SHIM,
    "// AUTO-GENERATED by node build-git.mjs — dist 入口指向 bundle(dist/server.mjs 的 import 路径)。\n" +
      'export * from "./git.mjs";\n',
    "utf8"
  );
  // 源目录不散落 dist(build.mjs 会把 src/git/ 一并直拷进来;装机只认 bundle 与一行入口)。
  rmSync(join(ROOT, "dist", "git"), { recursive: true, force: true });
  console.log("[build-git] dist/git.mjs(" + code.length + " 个字符,code.length(UTF-16 码元);入口 " + ENTRY + ")");
  return OUT;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildGitBundle().catch((e) => {
    console.error(e && e.stack ? e.stack : e);
    process.exit(1);
  });
}
